def buildPrompt(user_message: str, context_docs: list[str]) -> str:
    """将检索到的文档拼成一个 RAG prompt"""
    if not context_docs:
        return user_message  # 如果没有文档，直接返回用户消息
    context_str = "\n\n".join([f"【参考资料 {i+1}】\n{doc}" for i, doc in enumerate(context_docs)])
    prompt=f"""你是一个育儿专家助手，请根据以下参考资料回答用户的问题。
    如果参考资料中没有相关信息，请根据你的知识礼貌回答。

    {context_str}

    用户问题： {user_message}
    回答："""
    return prompt

def buildPromptTest(user_message: str, context_docs: list[str]) -> str:
    """将检索到的文档拼成一个 RAG prompt，综合应用 Prompt Engineering 原则"""

    # 拼接参考文档
    if context_docs:
        context_str = "\n\n---\n\n".join(context_docs)
    else:
        context_str = "暂无相关参考资料"

    # Few-shot 示例（原则 1.4）
    few_shot = """
    示例 1：
    问题：宝宝打疫苗后发烧到 38.5 度，怎么办？
    回答：
    先给结论：这通常是正常的免疫反应，可以吃退烧药。
    原理一句话：疫苗就像给免疫系统看了一张通缉令，身体会主动升高体温来练兵。
    具体怎么做：1. 确认宝宝月龄（≥3月龄用对乙酰氨基酚，≥6月龄可用布洛芬）；2. 减少衣物，保持室温 24-26℃；3. 多喂奶/水。
    什么时候去医院：如果发烧超过 72 小时不退，或宝宝精神萎靡、拒绝吃奶，请立即就医。

    示例 2：
    问题：宝宝辅食可以加盐吗？
    回答：
    先给结论：1 岁以内不加盐。
    原理一句话：宝宝肾脏还没发育好，多余的钠排不出去，就像一个小水池无法处理大洪水。
    具体怎么做：1. 1岁前辅食完全不加盐和酱油；2. 可以用天然调味品（如番茄、南瓜、虾皮粉）提味；3. 避免给宝宝吃大人的饭菜。
    什么时候去医院：通常不需要，但如果宝宝出现水肿、尿量明显减少，需就医排查肾脏问题。
    """

    # 先分类再作答。**不能**把所有问题都按儿科问诊处理 ——
    # 问「你是谁」时会被硬套上五段式，输出「🚨 什么时候去医院：这个问题不用去医院😄」。
    prompt = f"""请先判断<用户问题>属于哪一类，再按对应方式作答。

    【A 类：育儿 / 宝宝健康问题】
    步骤一：先不看参考资料，基于你的医学知识给出初步回答。
    步骤二：阅读<参考资料>，核对初步回答；资料与问题无关就忽略它，不要被带偏。
    步骤三：生成最终回答，严格按下面这个格式，五个小节都不省略：
      🏷️ **先给结论**：
      📖 **原理一句话**：
      ✅ **具体怎么做**：
      🚨 **什么时候去医院**：
      🩺 **免责声明**：
    参考资料与问题无关时，用你自己的医学知识回答即可。**不要**向用户提及「知识库」
    「参考资料」这类内部机制，也不要因为资料不相关就拒绝回答。

    【B 类：与育儿无关的问题】（询问你是谁、闲聊、其他领域的问题……）
    简短、友好地直接回答即可。**不要**套用上面的五段式结构 ——
    尤其不要出现「什么时候去医院」这种与问题毫无关系的小节，
    也不要编造就医建议或补一段免责声明。

    <参考资料>
    {context_str}
    </参考资料>

    <用户问题>
    {user_message}
    </用户问题>

    下面两个示例演示的是 A 类问题的格式与语气，**仅 A 类模仿**：
    {few_shot}

    你的回答："""
    return prompt
